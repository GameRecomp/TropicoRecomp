//! The LZMA decoder against streams made by xz from generated text (words
//! picked by a small LCG), in the framing Inno Setup uses: LZMA1 with five
//! property bytes and an end marker, LZMA2 with its dictionary byte.

use rc_inno::Error;
use rc_inno::lzma;

/// The text the streams were made from.
fn input() -> Vec<u8> {
    const W: &str = "island palace sugar tobacco rum cigar farm dock harbor church clinic \
                     school market road election rebel soldier tourist hotel beach";
    let words: Vec<&str> = W.split_whitespace().collect();
    let mut x: u32 = 12345;
    let mut out = Vec::new();
    while out.len() < 16000 {
        x = x.wrapping_mul(1_103_515_245).wrapping_add(12345) & 0x7fff_ffff;
        out.extend_from_slice(words[((x >> 16) as usize) % words.len()].as_bytes());
        out.push(if (x >> 8).is_multiple_of(13) {
            b'\n'
        } else {
            b' '
        });
    }
    out.truncate(16000);
    out
}

fn unhex(s: &str) -> Vec<u8> {
    (0..s.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap())
        .collect()
}

type Decoder = fn(&[u8], &mut dyn FnMut(&[u8]) -> Result<(), Error>) -> Result<u64, Error>;

fn run(f: Decoder, data: &[u8]) -> Result<Vec<u8>, Error> {
    let mut out = Vec::new();
    let n = f(data, &mut |b: &[u8]| {
        out.extend_from_slice(b);
        Ok(())
    })?;
    assert_eq!(n as usize, out.len());
    Ok(out)
}

fn lzma1(d: &[u8], s: &mut dyn FnMut(&[u8]) -> Result<(), Error>) -> Result<u64, Error> {
    lzma::lzma(d, s)
}

fn lzma2(d: &[u8], s: &mut dyn FnMut(&[u8]) -> Result<(), Error>) -> Result<u64, Error> {
    lzma::lzma2(d, s)
}

#[test]
fn lzma1_with_end_marker() {
    assert_eq!(run(lzma1, &unhex(LZMA1)).unwrap(), input());
}

#[test]
fn lzma2_chunks() {
    assert_eq!(run(lzma2, &unhex(LZMA2)).unwrap(), input());
}

#[test]
fn damage_is_an_error_not_a_panic() {
    let cases: [(Decoder, &str); 2] = [(lzma1, LZMA1), (lzma2, LZMA2)];
    for (f, s) in cases {
        let good = unhex(s);
        // Truncated anywhere.
        for cut in [1, 6, 7, good.len() / 2, good.len() - 1] {
            assert!(run(f, &good[..cut]).map(|o| o != input()).unwrap_or(true));
        }
        // A flipped byte in the middle, at several places.
        for at in (10..good.len()).step_by(7) {
            let mut bad = good.clone();
            bad[at] ^= 0x55;
            let _ = run(f, &bad);
        }
    }
}

